        internal static string[] Sections(ComplaintView c)
        {
            int index = c.Kind == ComplaintKind.Opposition ? 27 : c.Kind == ComplaintKind.Suggestion ? 28 : c.Odd ? 26 : c.Key % ComplaintRules.Slots;
            if (index < 0 || index >= Texts.Length) return new string[] { "", "" };
            return L.T(Texts[index]).Split(new char[] { '\n' }, 2);
        }
